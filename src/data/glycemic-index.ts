export function findGI(ingredientName: string): number | null {
  const lower = ingredientName.toLowerCase();
  let bestMatch: GIEntry | null = null;
  let bestLength = 0;

  for (const entry of GI_DATABASE) {
    for (const kw of entry.keywords) {
      if (lower.includes(kw) && kw.length > bestLength) {
        bestMatch = entry;
        bestLength = kw.length;
      }
    }
  }

  return bestMatch?.gi ?? null;
}

export type GLCategory = 'Low' | 'Medium' | 'High';

export function glCategory(gl: number): GLCategory {
  if (gl <= 10) return 'Low';
  if (gl <= 19) return 'Medium';
  return 'High';
}

export function glCategoryColor(category: GLCategory): string {
  switch (category) {
    case 'Low': return 'bg-emerald-100 text-emerald-700';
    case 'Medium': return 'bg-amber-100 text-amber-700';
    case 'High': return 'bg-red-100 text-red-700';
  }
}

