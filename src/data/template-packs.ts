import type { TemplateSection, TemplateTheme } from '@/lib/types';

export interface TemplatePack {
  id: string;
  name: string;
  category: 'seasonal' | 'style' | 'occasion' | 'professional';
  description: string;
  templates: TemplatePackTemplate[];
}

export interface TemplatePackTemplate {
  id: string;
  name: string;
  type: 'recipe' | 'book-page' | 'book-recipe';
  description: string;
  sections: TemplateSection[];
  theme: TemplateTheme;
  pageSize: 'card' | 'a4' | 'letter';
  orientation: 'portrait' | 'landscape';
  margins: { top: number; right: number; bottom: number; left: number };
}

function section(
  type: TemplateSection['type'],
  order: number,
  column: 1 | 2,
  style?: TemplateSection['style'],
): TemplateSection {
  return {
    id: crypto.randomUUID(),
    type,
    visible: true,
    order,
    column,
    style: style ?? {},
  };
}

