#!/usr/bin/env node

import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));

const USA_REGION_MAP = {
  Northeast: ['CT', 'DE', 'DC', 'ME', 'MD', 'MA', 'NH', 'NJ', 'NY', 'PA', 'RI', 'VT'],
  Southeast: ['AL', 'AR', 'FL', 'GA', 'KY', 'LA', 'MS', 'NC', 'SC', 'TN', 'VA', 'WV'],
  Midwest: ['IL', 'IN', 'IA', 'KS', 'MI', 'MN', 'MO', 'NE', 'ND', 'OH', 'SD', 'WI'],
  Southwest: ['AZ', 'NM', 'OK', 'TX'],
  West: ['AK', 'CA', 'CO', 'HI', 'ID', 'MT', 'NV', 'OR', 'UT', 'WA', 'WY'],
};

const STATE_TO_REGION = {};
for (const [region, states] of Object.entries(USA_REGION_MAP)) {
  for (const state of states) {
    STATE_TO_REGION[state] = region;
  }
}

async function fetchBundleUrl() {
  console.error('Fetching seasonalfoodguide.org homepage...');
  const res = await fetch('https://www.seasonalfoodguide.org/');
  const html = await res.text();
  let match = html.match(/href=["']?(\/js\/app\.[a-f0-9]+\.js)["']?/);
  if (!match) match = html.match(/src=["']?(\/js\/app\.[a-f0-9]+\.js)["']?/);
  if (!match) throw new Error('Could not find JS bundle URL in homepage');
  return `https://www.seasonalfoodguide.org${match[1]}`;
}

async function extractProduceData(bundleUrl) {
  console.error(`Fetching bundle: ${bundleUrl}`);
  const res = await fetch(bundleUrl);
  const js = await res.text();

  const modulePattern = /6907:\s*\(?function\s*\(\w+\)\s*\{[^}]*JSON\.parse\(\s*'(\[.*?\])'\s*\)/s;
  let match = js.match(modulePattern);

  if (!match) {
    const altPattern = /JSON\.parse\(\s*'(\[\{.*?"produce".*?\}?\])'\s*\)/s;
    match = js.match(altPattern);
  }

  if (!match) {
    const simplePattern = /var\s+\w+\s*=\s*JSON\.parse\(\s*'(\[.*?\])'\s*\)/s;
    const allMatches = [...js.matchAll(new RegExp(simplePattern.source, 'sg'))];
    for (const m of allMatches) {
      try {
        const parsed = JSON.parse(m[1]);
        if (Array.isArray(parsed) && parsed.length > 100 && parsed[0]?.name && parsed[0]?.season) {
          match = m;
          break;
        }
      } catch {}
    }
  }

  if (!match) {
    throw new Error('Could not extract produce data from JS bundle. The source site structure may have changed.');
  }

  const jsonStr = match[1].replace(/\\'/g, "'").replace(/\\\\/g, '\\');
  const produce = JSON.parse(jsonStr);
  console.error(`Extracted ${produce.length} produce items`);
  return produce;
}

function convertToMonthly(regionProduce) {
  const monthly = {};
  for (let month = 1; month <= 12; month++) {
    monthly[month] = [];
  }

  for (const item of regionProduce) {
    const allPeriods = new Set();
    for (const stateData of Object.values(item.states)) {
      if (stateData.seasons) {
        for (const p of stateData.seasons) allPeriods.add(p);
      }
    }

    for (let month = 1; month <= 12; month++) {
      const period1 = (month - 1) * 2 + 1;
      const period2 = period1 + 1;
      if (allPeriods.has(period1) || allPeriods.has(period2)) {
        monthly[month].push(item.name);
      }
    }
  }

  for (let month = 1; month <= 12; month++) {
    monthly[month] = [...new Set(monthly[month])].sort((a, b) =>
      a.toLowerCase().localeCompare(b.toLowerCase())
    );
  }

  return monthly;
}

function aggregateByRegion(produce) {
  const regionData = {};

  for (const [regionName, states] of Object.entries(USA_REGION_MAP)) {
    const regionProduce = produce.filter(item => {
      if (!item.states) return false;
      return Object.keys(item.states).some(s => states.includes(s));
    }).map(item => {
      const filteredStates = {};
      for (const state of states) {
        if (item.states[state]) {
          filteredStates[state] = item.states[state];
        }
      }
      return { name: item.name, states: filteredStates };
    });

    regionData[regionName] = convertToMonthly(regionProduce);
  }

  return regionData;
}

function generateOutputFile(regionData) {
  const regionEntries = Object.entries(regionData);

  const tsContent = `// Auto-generated by scripts/scrape-seasonal-produce.mjs
// DO NOT EDIT MANUALLY — re-run the script to update

export const USA_REGIONS: string[] = ${JSON.stringify(Object.keys(USA_REGION_MAP), null, 2)};

export const USA_STATES_TO_REGION: Record<string, string> = ${JSON.stringify(STATE_TO_REGION, null, 2)};

export const DEFAULT_SEASONAL_FOODS: Record<string, Record<number, string[]>> = {
${regionEntries.map(([region, months]) =>
    `  "${region}": {\n${Object.entries(months).map(([month, foods]) =>
      `    ${month}: ${JSON.stringify(foods)}`
    ).join(',\n')}\n  }`
  ).join(',\n')}
};
`;

  return tsContent;
}

async function main() {
  try {
    const bundleUrl = await fetchBundleUrl();
    const produce = await extractProduceData(bundleUrl);
    const regionData = aggregateByRegion(produce);
    const tsContent = generateOutputFile(regionData);

    const outputPath = join(__dirname, '..', 'src', 'data', 'seasonal-produce.ts');
    writeFileSync(outputPath, tsContent, 'utf-8');
    console.error(`Wrote ${tsContent.split('\n').length} lines to ${outputPath}`);

    const totalFoods = Object.values(regionData).reduce(
      (sum, months) => sum + Object.values(months).reduce((s, foods) => s + foods.length, 0), 0
    );
    console.error(`Total entries: ${totalFoods} across ${Object.keys(regionData).length} regions`);
  } catch (err) {
    console.error('Error:', err.message);
    process.exit(1);
  }
}

main();
